"""中文分词：BM25 索引和查询共用同一套分词规则。

**为什么必须共用**：BM25 是按「词」匹配的。如果建索引时把「长春功」切成一个词、
查询时切成「长春」+「功」，那这两边的词表根本对不上，检索必然失败。所以分词
规则只能有一份，放在这里给 ingest（建索引）和 rag（查询）共同调用。
"""
import jieba

# 分词后过滤掉的常见虚词/疑问词——这些词本身不携带查找价值。
# 注意：BM25 的 IDF 其实已经能自动压低常见词的权重（一个词出现在越多文档里，
# 它的 IDF 越小），所以停用词表不像在纯关键词匹配时代那么关键了。这里保留它
# 主要是为了减小索引体积——把「的」「了」这类词存进倒排索引纯属浪费空间。
_STOPWORDS = frozenset({
    "的", "了", "是", "在", "有", "和", "与", "就", "都", "而", "及", "或",
    "着", "过", "也", "还", "又", "但", "却", "让", "被", "把", "从", "到",
    "对", "给", "向", "以", "为", "之", "其中", "这", "那", "一下", "一些",
    "自己", "没有", "这些", "那些",
    # jieba 会把「这个」「那个」切成一个词，光有「这」「那」拦不住。
    # 实测「这个」在语料里出现在 6807 个片段中，纯噪声却参与打分。
    "这个", "那个", "一个", "某个", "里面", "上面", "下面", "时候",
    "什么", "哪些", "怎么", "为什么", "吗", "呢", "啊", "吧",
    "可以", "可能", "应该", "会不会", "是不是", "有没有", "多少", "怎样",
    "如何", "为何", "何时", "哪里", "哪个", "以及", "还有", "然后", "讲讲",
    "详细", "介绍",
})


def tokenize(text: str) -> list[str]:
    """把文本切成词表（保留重复，因为 BM25 需要词频 tf）。

    过滤规则：
    - 长度 < 2 的丢掉。中文单字（"的""了"）几乎都是虚词；即使不是虚词，
      单字检索对缩小范围也没帮助（"韩"命中的片段和"韩立"命中的差不多，
      但会把不相关的"韩"姓配角也拉进来）。
    - 停用词丢掉（见上面 _STOPWORDS 的说明）。

    返回的是**带重复的列表**而不是集合——调用方要靠重复次数算词频。
    """
    return [
        token
        for token in (t.strip() for t in jieba.cut(text))
        if len(token) >= 2 and token not in _STOPWORDS
    ]


def term_frequencies(text: str) -> dict[str, int]:
    """统计每个词在这段文本里出现几次，用于写倒排索引。"""
    counts: dict[str, int] = {}
    for token in tokenize(text):
        counts[token] = counts.get(token, 0) + 1
    return counts


def query_terms(question: str) -> list[str]:
    """把用户的问题切成查询词（去重，顺序保持稳定）。

    查询侧去重是因为 BM25 打分时同一个词算两遍没有意义——用户问
    "韩立和韩立的师父"，「韩立」重复出现不该让它的权重翻倍。
    （文档侧则相反，重复次数正是 tf，是有意义的信号。）
    """
    seen: list[str] = []
    for token in tokenize(question):
        if token not in seen:
            seen.append(token)
    return seen
